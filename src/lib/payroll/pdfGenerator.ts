import { PDFDocument, rgb, StandardFonts } from 'pdf-lib';
import { PayrollRow, Token } from './types';
import { getArcNetwork } from '../chain/constants';

export async function generatePayslipPdf(
  row: PayrollRow,
  runTitle: string,
  token: Token,
  txHash?: string
): Promise<Uint8Array> {
  const pdfDoc = await PDFDocument.create();
  const page = pdfDoc.addPage([600, 400]);
  const { width, height } = page.getSize();

  const fontBold = await pdfDoc.embedFont(StandardFonts.HelveticaBold);
  const fontRegular = await pdfDoc.embedFont(StandardFonts.Helvetica);

  // Header Bar (Olive Green #3D5A35 -> RGB: 0.239, 0.353, 0.208)
  page.drawRectangle({
    x: 0,
    y: height - 70,
    width,
    height: 70,
    color: rgb(0.239, 0.353, 0.208),
  });

  page.drawText('PAYRUN | OFFICIAL PAYSLIP RECEIPT', {
    x: 30,
    y: height - 42,
    size: 16,
    font: fontBold,
    color: rgb(0.98, 0.96, 0.94),
  });

  page.drawText(`Arc Network Transaction Verified`, {
    x: 30,
    y: height - 58,
    size: 9,
    font: fontRegular,
    color: rgb(0.85, 0.92, 0.82),
  });

  // Body Content
  let y = height - 110;

  // Title / Batch
  page.drawText('BATCH TITLE:', { x: 30, y, size: 9, font: fontBold, color: rgb(0.35, 0.43, 0.32) });
  page.drawText(runTitle || 'Standard Payroll Run', { x: 140, y, size: 10, font: fontRegular, color: rgb(0.15, 0.22, 0.13) });

  y -= 25;
  page.drawText('RECIPIENT NAME:', { x: 30, y, size: 9, font: fontBold, color: rgb(0.35, 0.43, 0.32) });
  page.drawText(row.name, { x: 140, y, size: 10, font: fontBold, color: rgb(0.15, 0.22, 0.13) });

  y -= 25;
  page.drawText('WALLET ADDRESS:', { x: 30, y, size: 9, font: fontBold, color: rgb(0.35, 0.43, 0.32) });
  page.drawText(row.address, { x: 140, y, size: 9, font: fontRegular, color: rgb(0.15, 0.22, 0.13) });

  y -= 25;
  page.drawText('MEMO / REFERENCE:', { x: 30, y, size: 9, font: fontBold, color: rgb(0.35, 0.43, 0.32) });
  page.drawText(row.memo || 'N/A', { x: 140, y, size: 10, font: fontRegular, color: rgb(0.15, 0.22, 0.13) });

  y -= 35;
  // Divider
  page.drawLine({
    start: { x: 30, y },
    end: { x: width - 30, y },
    thickness: 1,
    color: rgb(0.9, 0.87, 0.8),
  });

  y -= 30;
  // Amount Highlight Box
  page.drawRectangle({
    x: 30,
    y: y - 15,
    width: width - 60,
    height: 40,
    color: rgb(0.95, 0.93, 0.88),
  });

  page.drawText('TOTAL AMOUNT PAID:', { x: 45, y: y + 2, size: 11, font: fontBold, color: rgb(0.239, 0.353, 0.208) });
  page.drawText(`${row.amount} ${token}`, { x: 400, y: y + 2, size: 16, font: fontBold, color: rgb(0.239, 0.353, 0.208) });

  y -= 50;
  if (txHash) {
    page.drawText('TRANSACTION HASH:', { x: 30, y, size: 8, font: fontBold, color: rgb(0.4, 0.4, 0.4) });
    page.drawText(txHash, { x: 140, y, size: 8, font: fontRegular, color: rgb(0.2, 0.4, 0.8) });
  }

  // Footer Note
  const netConfig = getArcNetwork();
  page.drawText(`Generated by PayRun on Arc Network • Chain ID ${netConfig.chainId}`, {
    x: 30,
    y: 25,
    size: 8,
    font: fontRegular,
    color: rgb(0.5, 0.5, 0.5),
  });

  return await pdfDoc.save();
}

